export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      return localStorage.getItem('shloka_language') || 'EN';
    } catch (e) {
      return 'EN';
    }
  });

  const setLanguage = (lang) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('shloka_language', lang);
    } catch (e) {}
  };

  const toggleLanguage = () => {
    setLanguage(language === 'EN' ? 'HI' : 'EN');
  };

  // Helper function to resolve dot-notated keys e.g. t('hero.title')
  const t = (path, fallback = '') => {
    if (!path) return fallback;
    const parts = path.split('.');
    let curr = translations[language] || translations.EN;
    for (const part of parts) {
      if (curr && curr[part] !== undefined) {
        curr = curr[part];
      } else {
        // Fallback to English if translation is missing
        let enCurr = translations.EN;
        for (const p of parts) {
          if (enCurr && enCurr[p] !== undefined) {
            enCurr = enCurr[p];
          } else {
            return fallback || path;
          }
        }
        return enCurr || fallback || path;
      }
    }
    return curr;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, toggleLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}

export default LanguageContext;
